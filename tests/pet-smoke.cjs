// 桌宠窗口冒烟测试：召唤、气泡、点击反应、拖拽移动、关闭与持久化。
// 用户数据与主界面测试一样隔离到临时目录。
const { app, BrowserWindow, Notification, screen } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const temp = process.env.WHALE_TEST_USER_DATA;
if (!temp) throw new Error('Run this test using npm run test:pet');
app.setPath('userData', temp);
app.commandLine.appendSwitch('disable-renderer-backgrounding');
Notification.isSupported = () => false;
const errors = [];
app.on('web-contents-created', (_event, contents) => {
  contents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message); });
  contents.on('preload-error', (_event, _file, error) => errors.push(error.message));
  contents.on('render-process-gone', (_event, details) => errors.push(details.reason));
});
let cursorPoint = { x:0, y:0 };
require('../main');

const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const js = (code, win) => win.webContents.executeJavaScript(code, true);
async function untilMain(check, label) {
  for (let i = 0; i < 100; i++) {
    if (check()) return;
    await pause(50);
  }
  throw new Error(`Timed out: ${label}`);
}
async function until(code, win, label) {
  for (let i = 0; i < 100; i++) {
    if (await js(code, win)) return;
    await pause(50);
  }
  throw new Error(`Timed out: ${label}`);
}
async function shot(name, win) {
  await pause(200);
  const folder = path.join(__dirname, '..', '.screenshots');
  fs.mkdirSync(folder, { recursive: true });
  fs.writeFileSync(path.join(folder, name), (await win.webContents.capturePage()).toPNG());
}

app.whenReady().then(async () => {
  screen.getCursorScreenPoint = () => ({ ...cursorPoint });
  try {
    const main = BrowserWindow.getAllWindows()[0];
    assert.ok(main, 'production window created');
    await until(`document.getElementById('todoList')?.getAttribute('aria-busy') === 'false'`, main, 'initial load');
    await until(`document.getElementById('btnPet')?.getAttribute('aria-pressed') === 'false'`, main, 'pet button ready');

    // 召唤桌宠
    assert.deepEqual(await js(`window.api.togglePet()`, main), { enabled: true });
    await untilMain(() => BrowserWindow.getAllWindows().length === 2, 'pet window opens');
    const pet = BrowserWindow.getAllWindows().find(w => w !== main);
    assert.ok(pet, 'pet window exists');
    assert.equal(await js(`document.getElementById('petBody')?.naturalWidth`, pet), 1024, 'full-body art loads');
    await until(`document.getElementById('petBubble').classList.contains('show')`, pet, 'greet bubble');
    await shot('pet-window.png', pet);

    // 点击身体 → 反应气泡 + 摆动
    await pet.webContents.sendInputEvent({ type: 'mouseMove', x: 105, y: 200 });
    await pause(120);
    await pet.webContents.sendInputEvent({ type: 'mouseDown', x: 105, y: 200, button: 'left', clickCount: 1 });
    await pause(60);
    await pet.webContents.sendInputEvent({ type: 'mouseUp', x: 105, y: 200, button: 'left' });
    await until(`document.getElementById('petBubble').classList.contains('show')`, pet, 'click bubble');
    await until(`!dragging && !finishingDrag && document.getElementById('petFigure').classList.contains('woke')`, pet, 'wiggle on click after drag IPC settles');

    // 注视引擎管线（真实光标无法编程移动，直接验证 CSS 变量驱动表情层变换）
    await js(`document.documentElement.style.setProperty('--gx', '0.7'); document.documentElement.style.setProperty('--gy', '-0.4')`, pet);
    await pause(150);
    const transform = await js(`getComputedStyle(document.querySelector('.pet-face-fx')).transform`, pet);
    assert.notEqual(transform, 'none', 'face layer follows gaze vars');

    // Moving the native cursor must move the window exactly once, regardless of
    // the synthetic local mouse events generated by the window moving underneath it.
    const before = pet.getBounds();
    cursorPoint = { x:before.x+105, y:before.y+160 };
    const anchor = { ...cursorPoint };
    await pet.webContents.sendInputEvent({ type:'mouseDown', x:105, y:160, button:'left', clickCount:1 });
    await pause(100);
    for (let i=1; i<=12; i++) {
      cursorPoint = { x:anchor.x+i*4, y:anchor.y-i*3 };
      await pet.webContents.sendInputEvent({ type:'mouseMove', x:105, y:160 });
      await pause(45);
      const current = pet.getBounds();
      assert.ok(Math.abs(current.x-before.x-i*4)<=1 && Math.abs(current.y-before.y+i*3)<=1, `screen anchor followed exactly at step ${i}`);
    }
    assert.equal(await js(`motion.mode`,pet),'walkSide','horizontal drag plays walking frames');
    assert.equal(await js(`motion.direction`,pet),'right');
    await shot('pet-drag-walk-right.png',pet);
    for (let i=1;i<=9;i++) {
      cursorPoint={x:anchor.x+48-i*6,y:anchor.y-36}; await pause(45);
    }
    await until(`motion.mode==='walkSide' && motion.direction==='left'`,pet,'reverse drag walks left');
    assert.equal(await js(`$('petFigure').classList.contains('walking-left')`,pet),true);
    await shot('pet-drag-walk-left.png',pet);
    await pause(220);
    assert.equal(await js(`motion.mode`,pet),'dragStand','stationary horizontal drag stops stepping');
    const stoppedFrame=await js(`$('petWalkSideAtlas').dataset.frame`,pet); await pause(200);
    assert.equal(await js(`$('petWalkSideAtlas').dataset.frame`,pet),stoppedFrame);
    for (let i=1;i<=8;i++) { cursorPoint={x:anchor.x-6,y:anchor.y-36-i*6};await pause(45); }
    await until(`motion.mode==='drag'`,pet,'upward drag lifts character');
    for (let i=1;i<=8;i++) { cursorPoint={x:anchor.x-6,y:anchor.y-84+i*6};await pause(45); }
    await until(`motion.mode==='dragLower'`,pet,'downward drag lowers character');
    const stationary = pet.getBounds();
    for(let i=0;i<8;i++) {
      await pet.webContents.sendInputEvent({ type:'mouseMove', x:100+i%3, y:160 });
      await pause(25);
      assert.deepEqual(pet.getBounds(),stationary,'stationary cursor never feeds window movement back into drag');
    }
    assert.equal(await js(`motion.mode`,pet),'dragLower');
    assert.equal(await js(`getComputedStyle(document.getElementById('petFigure')).animationName`,pet),'none','no competing shake animation while dragging');
    const dragFrame = await js(`document.getElementById('petDragAtlas').style.left`,pet);
    await pause(380);
    assert.equal(await js(`document.getElementById('petDragAtlas').style.left`,pet),dragFrame,'held pose does not alternate');
    await shot('pet-drag-stable.png',pet);
    await pet.webContents.sendInputEvent({ type:'mouseUp', x:105, y:160, button:'left' });
    await until(`!finishingDrag`,pet,'drag finishes');
    const after = pet.getBounds();
    assert.equal(after.x-before.x,-6); assert.equal(after.y-before.y,-36);
    await until(`motion.mode==='idle' || motion.mode==='sleep'`,pet,'landing finishes');

    // A stalled renderer must hold the next pose, not drain pre-scheduled timers.
    await js(`sleeping=false; sleepOverride=false; playSequence('greeting','petGreetingAtlas',[[0,10],[1,10],[2,10],[3,10]]); const busyUntil=performance.now()+600; while(performance.now()<busyUntil) {}`,pet);
    await until(`$('petGreetingAtlas').dataset.frame==='1'`,pet,'next pose after renderer stall');
    await pause(100);
    assert.equal(await js(`$('petGreetingAtlas').dataset.frame`,pet),'1','delayed frames keep their own dwell time');
    await until(`motion.mode==='idle'`,pet,'paced greeting completes');

    // Simulated IPC/DOM events must not expose a neighboring sprite cell.
    await js(`sleepOverride=false; sleeping=false; setMotion('idle'); clearMotionTimers(); atlasFrame('petIdleAtlas',2,1); $('petFigure').style.animation='none'; $('petBubble').classList.remove('show');`,pet);
    await shot('pet-idle-clipped.png',pet);
    await js(`document.body.style.background='#fff'`,pet);
    await shot('pet-no-shadow-white.png',pet);
    await js(`document.body.style.background=''`,pet);
    for (const [id,columns,rows,frame] of [['petIdleAtlas',2,2,1],['petWalkAtlas',4,2,5],['petLifeAtlas',4,3,7]]) {
      const original = await js(`$("${id}").src`,pet);
      await js(`(async()=>{
        setMotion('${id==='petIdleAtlas'?'idle':id==='petWalkAtlas'?'walk':'life'}'); clearMotionTimers();
        const canvas=document.createElement('canvas'); canvas.width=${columns*100}; canvas.height=${rows*100};
        const ctx=canvas.getContext('2d'); ctx.fillStyle='#00ff00';ctx.fillRect(0,0,canvas.width,canvas.height);
        ctx.fillStyle='#ff0000';ctx.fillRect(${frame%columns*100},${Math.floor(frame/columns)*100},100,100);
        $('${id}').src=canvas.toDataURL();await $('${id}').decode();
        renderAtlasCell('${id}',${columns},${rows},${frame},${columns===2?176:264});
      })()`,pet);
      await pause(150);
      const capture=await pet.webContents.capturePage(); const pixels=capture.toBitmap(); let leaked=0;
      for(let i=0;i<pixels.length;i+=4) if(pixels[i+1]>230 && pixels[i]<20 && pixels[i+2]<20 && pixels[i+3]>230) leaked++;
      assert.equal(leaked,0,`${id}: neighboring green cells are completely clipped`);
      await js(`$('${id}').src=${JSON.stringify(original)}; $('${id}').decode()`,pet);
    }
    await js(`$('petSprite').style.filter='';setMotion('idle')`,pet);

    // 收回桌宠并确认状态持久化
    assert.deepEqual(await js(`window.api.togglePet()`, main), { enabled: false });
    await untilMain(() => BrowserWindow.getAllWindows().length === 1, 'pet window closes');
    await pause(150);
    const saved = JSON.parse(fs.readFileSync(path.join(temp, 'pet-state.json'), 'utf8'));
    assert.equal(saved.enabled, false);
    assert.equal(await js(`document.getElementById('btnPet').getAttribute('aria-pressed')`, main), 'false');

    // 再次召唤时恢复上次位置
    assert.deepEqual(await js(`window.api.togglePet()`, main), { enabled: true });
    await untilMain(() => BrowserWindow.getAllWindows().length === 2, 'pet returns');
    const pet2 = BrowserWindow.getAllWindows().find(w => w !== main);
    const restored = pet2.getBounds();
    assert.ok(Math.abs(restored.x - after.x) <= 2 && Math.abs(restored.y - after.y) <= 2, 'position restored');
    await shot('pet-gaze.png', pet2);

    assert.deepEqual(errors, [], 'no renderer, CSP, preload or process errors');
    console.log('PASS: pet summon/dismiss, full-body art, greet and click bubbles, wiggle, gaze pipeline, absolute screen drag, stationary stability, directional walking/lift/lower, stable pause, per-cell pixel clipping, position persistence.');
    console.log('Screenshots: .screenshots/pet-window.png, pet-gaze.png');
    app.exit(0);
  } catch (error) {
    console.error(error.stack || error);
    console.error('Renderer errors:', errors);
    app.exit(1);
  }
});
